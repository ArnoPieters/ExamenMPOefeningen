
public class TimeOfDay {
	private int hours;
	private int minutes;
	public TimeOfDay(int hours,int minutes) {
		this.hours = hours;
		this.minutes = minutes;
	}
	
	public void setHours(int hour) {
		hours = hour;
	}
	public void setMinutes(int minute) {
		minutes = minute;
	}
	public int getHours() {
		return hours;
	}
	public int getMinutes() {return minutes;}
	
	
	
}
